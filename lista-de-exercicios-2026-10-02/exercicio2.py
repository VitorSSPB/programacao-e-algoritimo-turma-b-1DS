# Programa que recebe dois números e exibe os resultados das quatro operações básicas na tela.

a = float(input("Digite o primeiro número: "))
b = float(input("Digite o segundo número: "))

soma = a + b
sub = a - b
mult = a * b
div = a / b

print(f"Soma: {soma}")
print(f"Subtração: {sub}")
print(f"Multiplicação: {mult}")
print(f"Divisão: {div}")